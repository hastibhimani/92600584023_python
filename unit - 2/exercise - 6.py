
# 1. List
fruits = ["Apple", "Banana", "Mango"]

print("List:")
for fruit in fruits:
    print(fruit)

# 2. String
name = "Python"

print("\nString:")
for char in name:
    print(char)

# 3. Dictionary
student = {
    "name": "Hasti",
    "age": 20,
    "course": "MCA"
}

print("\nDictionary:")
for key, value in student.items():
    print(key, ":", value)
